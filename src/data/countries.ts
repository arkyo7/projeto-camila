/** Remove acentos e normaliza para busca tolerante. */
export function normalizeSearch(value: string): string {
  return value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim();
}

const searchIndex = new Map<string, string>();
for (const country of countries) {
  searchIndex.set(
    country.code,
    [country.code, ...Object.values(country.names)].map(normalizeSearch).join(" | "),
  );
}

export function matchesCountry(country: Country, query: string): boolean {
  const q = normalizeSearch(query);
  if (!q) return true;
  if (q.replace(/^\+/, "") && country.dial.startsWith(q.replace(/^\+/, ""))) return true;
  return (searchIndex.get(country.code) ?? "").includes(q);
}

export function findCountry(code: string | undefined): Country | undefined {
  return countries.find((c) => c.code === code);
}
